-- The app connects as the table owner, which bypasses RLS. Enabling it with no policies
-- keeps these tables closed to Supabase's public REST API (anon / authenticated keys).
alter table public.app_users         enable row level security;
alter table public.migration_uploads enable row level security;
alter table public.migration_records enable row level security;

-- Every upload is kept. These views give the main authority each district's most recent upload
-- (the one with the highest id) and its rows, e.g.
--   select * from public.migration_records_latest where district_id = 'DST-02';
-- security_invoker (Postgres 15+) makes the views obey the tables' row level security.
create or replace view public.migration_latest_uploads with (security_invoker = true) as
select distinct on (district_id) *
from public.migration_uploads
order by district_id, id desc;

create or replace view public.migration_records_latest with (security_invoker = true) as
select r.*
from public.migration_records r
join public.migration_latest_uploads l on l.id = r.upload_id;
