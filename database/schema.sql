-- Migration table upload module.
-- Run this once in Supabase: Dashboard -> SQL Editor -> paste -> Run.

-- People who can upload. These are demo officers; replace with real users later.
create table if not exists public.app_users (
    user_id     text primary key,
    full_name   text not null,
    designation text not null
);

-- One row per uploaded CSV file, with the ID of the officer who uploaded it.
create table if not exists public.migration_uploads (
    id          bigint generated by default as identity primary key,
    file_name   text        not null,
    uploaded_by text        not null references public.app_users (user_id),
    uploaded_at timestamptz not null default now(),
    row_count   integer     not null
);

-- One row per line of the CSV ("Format - Migration table").
create table if not exists public.migration_records (
    id          bigint generated by default as identity primary key,
    upload_id   bigint  not null references public.migration_uploads (id) on delete cascade,
    uploaded_by text    not null references public.app_users (user_id),
    row_no      integer not null, -- line number in the uploaded file (header is line 1)
    ac_no_name  text    not null, -- e.g. 201-abc

    -- Existing Position
    existing_part_no   integer not null,
    existing_part_name text    not null,
    existing_section   text    not null,
    breakup_type       text,              -- e.g. Elector; blank when the part is not broken up
    existing_electors  text    not null,  -- a count (600) or an elector serial range (1001-1600)

    -- Rationalization - Activity Identification
    rationalized_part_no   text    not null, -- e.g. 2 or 2N1 for a newly created part
    rationalized_part_name text    not null,
    rationalized_section   text    not null,
    rationalized_electors  integer not null,
    action                 text    not null
);

create index if not exists migration_uploads_uploaded_by_idx on public.migration_uploads (uploaded_by);
create index if not exists migration_records_upload_id_idx on public.migration_records (upload_id);
create index if not exists migration_records_uploaded_by_idx on public.migration_records (uploaded_by);

-- The app connects as the table owner, which bypasses RLS. Enabling it with no policies
-- keeps these tables closed to Supabase's public REST API (anon / authenticated keys).
alter table public.app_users         enable row level security;
alter table public.migration_uploads enable row level security;
alter table public.migration_records enable row level security;

